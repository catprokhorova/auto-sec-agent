"""AWS Bedrock client wrapper for Claude 3.5 Sonnet and Haiku with mock fallback."""

import asyncio
import logging
import uuid
from typing import Any

from pydantic import BaseModel, Field

from src.core.config import Settings, get_settings

try:
    import boto3
    from botocore.config import Config as BotoConfig
    from botocore.exceptions import ClientError
except ImportError:  # pragma: no cover
    boto3 = None
    BotoConfig = None
    ClientError = Exception

logger = logging.getLogger(__name__)


class ToolCall(BaseModel):
    """Structured tool invocation emitted by LLM."""

    id: str = Field(description="Unique tool call identifier")
    name: str = Field(description="Name of the tool to invoke")
    arguments: dict[str, Any] = Field(
        default_factory=dict, description="Parsed arguments dictionary"
    )


class LLMResponse(BaseModel):
    """Standardized LLM response object."""

    content: str = Field(default="", description="Text content generated by the model")
    tool_calls: list[ToolCall] = Field(
        default_factory=list, description="Tool calls requested by the model"
    )
    stop_reason: str = Field(
        default="end_turn",
        description="Reason the model stopped ('end_turn', 'tool_use', 'max_tokens')",
    )
    input_tokens: int = Field(default=0, description="Tokens consumed in prompt")
    output_tokens: int = Field(default=0, description="Tokens generated in completion")
    model: str = Field(description="Model identifier used for generation")


class BedrockClient:
    """Async client managing AWS Bedrock Claude models with resilient mock mode."""

    def __init__(
        self,
        settings: Settings | None = None,
        force_mock: bool | None = None,
    ):
        self.settings = settings or get_settings()
        self.mock_mode = (
            force_mock
            if force_mock is not None
            else (self.settings.use_mock_llm or boto3 is None)
        )
        self._mock_response_queue: list[LLMResponse] = []
        self._bedrock_client = None

    def _get_boto_client(self) -> Any:
        """Initialize or retrieve boto3 bedrock-runtime client."""
        if self._bedrock_client is not None:
            return self._bedrock_client

        if boto3 is None:
            raise RuntimeError("boto3 is not installed.")

        boto_config = BotoConfig(
            retries={"max_attempts": 3, "mode": "standard"},
            read_timeout=120,
            connect_timeout=10,
        )

        kwargs: dict[str, Any] = {
            "service_name": "bedrock-runtime",
            "region_name": self.settings.aws_region,
            "config": boto_config,
        }

        if self.settings.aws_access_key_id and self.settings.aws_secret_access_key:
            kwargs["aws_access_key_id"] = self.settings.aws_access_key_id
            kwargs["aws_secret_access_key"] = self.settings.aws_secret_access_key

        self._bedrock_client = boto3.client(**kwargs)
        return self._bedrock_client

    def enqueue_mock_response(self, response: LLMResponse) -> None:
        """Queue a predetermined response for testing deterministic trajectories."""
        self._mock_response_queue.append(response)

    async def call_model(
        self,
        model_id: str,
        messages: list[dict[str, Any]],
        system_prompt: str | None = None,
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.0,
        max_tokens: int = 4096,
    ) -> LLMResponse:
        """Invoke Claude model via Bedrock Converse API or return realistic mock."""
        # 1. Custom mock queue check
        if self._mock_response_queue:
            return self._mock_response_queue.pop(0)

        # 2. Mock mode execution
        if self.mock_mode:
            return await self._generate_mock_response(
                model_id=model_id,
                messages=messages,
                system_prompt=system_prompt,
                tools=tools,
            )

        # 3. AWS Bedrock Runtime Converse API
        return await asyncio.to_thread(
            self._invoke_bedrock_converse_sync,
            model_id=model_id,
            messages=messages,
            system_prompt=system_prompt,
            tools=tools,
            temperature=temperature,
            max_tokens=max_tokens,
        )

    def _invoke_bedrock_converse_sync(
        self,
        model_id: str,
        messages: list[dict[str, Any]],
        system_prompt: str | None,
        tools: list[dict[str, Any]] | None,
        temperature: float,
        max_tokens: int,
    ) -> LLMResponse:
        """Synchronous wrapper for Bedrock converse call."""
        client = self._get_boto_client()

        # Format messages for Bedrock Converse API
        converse_messages: list[dict[str, Any]] = []
        for msg in messages:
            role = msg.get("role", "user")
            content = msg.get("content", "")
            if role in ["user", "assistant"]:
                if isinstance(content, str):
                    converse_messages.append(
                        {"role": role, "content": [{"text": content}]}
                    )
                elif isinstance(content, list):
                    converse_messages.append({"role": role, "content": content})

        request_kwargs: dict[str, Any] = {
            "modelId": model_id,
            "messages": converse_messages,
            "inferenceConfig": {
                "temperature": temperature,
                "maxTokens": max_tokens,
            },
        }

        if system_prompt:
            request_kwargs["system"] = [{"text": system_prompt}]

        if tools:
            request_kwargs["toolConfig"] = {"tools": tools}

        try:
            response = client.converse(**request_kwargs)
            output_msg = response.get("output", {}).get("message", {})
            stop_reason = response.get("stopReason", "end_turn")
            usage = response.get("usage", {})

            content_blocks = output_msg.get("content", [])
            text_chunks: list[str] = []
            tool_calls: list[ToolCall] = []

            for block in content_blocks:
                if "text" in block:
                    text_chunks.append(block["text"])
                elif "toolUse" in block:
                    tu = block["toolUse"]
                    tool_calls.append(
                        ToolCall(
                            id=tu.get("toolUseId", str(uuid.uuid4())),
                            name=tu.get("name", "unknown_tool"),
                            arguments=tu.get("input", {}),
                        )
                    )

            return LLMResponse(
                content="\n".join(text_chunks),
                tool_calls=tool_calls,
                stop_reason=stop_reason,
                input_tokens=usage.get("inputTokens", 0),
                output_tokens=usage.get("outputTokens", 0),
                model=model_id,
            )
        except Exception as exc:
            logger.warning(
                "AWS Bedrock converse failed (%s). Falling back to mock generator.",
                exc,
            )
            # Graceful fallback to mock response
            return self._generate_mock_response_sync(
                model_id=model_id,
                messages=messages,
                system_prompt=system_prompt,
                tools=tools,
            )

    async def _generate_mock_response(
        self,
        model_id: str,
        messages: list[dict[str, Any]],
        system_prompt: str | None = None,
        tools: list[dict[str, Any]] | None = None,
    ) -> LLMResponse:
        """Async generator for synthetic offline responses."""
        return await asyncio.to_thread(
            self._generate_mock_response_sync,
            model_id=model_id,
            messages=messages,
            system_prompt=system_prompt,
            tools=tools,
        )

    def _generate_mock_response_sync(
        self,
        model_id: str,
        messages: list[dict[str, Any]],
        system_prompt: str | None = None,
        tools: list[dict[str, Any]] | None = None,
    ) -> LLMResponse:
        """Produce realistic context-aware synthetic responses for testing."""
        last_message = messages[-1].get("content", "") if messages else ""
        combined_text = f"{system_prompt or ''} {last_message}".lower()

        # 1. Triage response (Identify vulnerability & target file)
        if "triage" in combined_text or "stack trace" in combined_text:
            text = (
                "{\n"
                '  "target_file": "services/auth/service.py",\n'
                '  "vulnerability_type": "SQL Injection (CWE-89)",\n'
                '  "cve_id": "CWE-89",\n'
                '  "summary": "User parameters concatenated directly into SQL statement",\n'
                '  "line_number": 18\n'
                "}"
            )
            return LLMResponse(
                content=text,
                stop_reason="end_turn",
                input_tokens=150,
                output_tokens=80,
                model=model_id,
            )

        # 2. Context fetching tool call request
        if ("fetch" in combined_text or "context" in combined_text) and tools:
            return LLMResponse(
                content="Fetching file content and impact radius.",
                tool_calls=[
                    ToolCall(
                        id=f"tool_{uuid.uuid4().hex[:8]}",
                        name="read_file",
                        arguments={"file_path": "services/auth/service.py"},
                    )
                ],
                stop_reason="tool_use",
                input_tokens=220,
                output_tokens=45,
                model=model_id,
            )

        # 3. Patch generation response
        if (
            "patch" in combined_text
            or "fix" in combined_text
            or "generate" in combined_text
        ):
            diff_text = (
                "```diff\n"
                "--- a/services/auth/service.py\n"
                "+++ b/services/auth/service.py\n"
                "@@ -17,2 +17,2 @@\n"
                "-    query = f\"SELECT id FROM users WHERE username = '{username}' AND password = '{password}'\"\n"
                "-    cursor.execute(query)\n"
                '+    query = "SELECT id FROM users WHERE username = ? AND password = ?"\n'
                "+    cursor.execute(query, (username, password))\n"
                "```"
            )
            return LLMResponse(
                content=diff_text,
                stop_reason="end_turn",
                input_tokens=350,
                output_tokens=120,
                model=model_id,
            )

        # Generic default response
        return LLMResponse(
            content="Analysis completed successfully.",
            stop_reason="end_turn",
            input_tokens=100,
            output_tokens=30,
            model=model_id,
        )

    async def generate_sonnet(
        self,
        messages: list[dict[str, Any]],
        system_prompt: str | None = None,
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.0,
    ) -> LLMResponse:
        """Call Claude 3.5 Sonnet for complex reasoning, planning, and patch generation."""
        return await self.call_model(
            model_id=self.settings.bedrock_model_sonnet,
            messages=messages,
            system_prompt=system_prompt,
            tools=tools,
            temperature=temperature,
        )

    async def generate_haiku(
        self,
        messages: list[dict[str, Any]],
        system_prompt: str | None = None,
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.0,
    ) -> LLMResponse:
        """Call Claude 3.5 Haiku for fast triage, token pruning, and summarizing."""
        return await self.call_model(
            model_id=self.settings.bedrock_model_haiku,
            messages=messages,
            system_prompt=system_prompt,
            tools=tools,
            temperature=temperature,
        )
